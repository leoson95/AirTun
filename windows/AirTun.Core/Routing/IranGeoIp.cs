    private static readonly Lazy<List<RouteEntry>> CachedRoutesTemplate = new(() =>
    {
        var list = new List<RouteEntry>(IranCidrs.Count);
        foreach (var cidr in IranCidrs)
        {
            var (dest, mask) = RouteEntry.ParseCidr(cidr);
            list.Add(new RouteEntry(dest, mask, string.Empty, 0, 10, cidr));
        }
        return list;
    });

    public static bool IsIranIp(string ipAddress)
    {
        if (string.IsNullOrWhiteSpace(ipAddress)) return false;
        if (!System.Net.IPAddress.TryParse(ipAddress.Trim(), out var ip) || ip.AddressFamily != System.Net.Sockets.AddressFamily.InterNetwork)
            return false;
        return IsIranIp(ip);
    }

    public static bool IsIranIp(System.Net.IPAddress ip)
    {
        if (ip.AddressFamily != System.Net.Sockets.AddressFamily.InterNetwork) return false;
        var b = ip.GetAddressBytes();
        uint ipUint = BitConverter.ToUInt32(b, 0);
        var template = CachedRoutesTemplate.Value;
        for (int i = 0; i < template.Count; i++)
        {
            if (template[i].ContainsIp(ipUint))
                return true;
        }
        return false;
    }

    public static IReadOnlyList<RouteEntry> CreateIranRoutes(string gateway, int interfaceIndex = 0, int metric = 10)
    {
        var routes = new List<RouteEntry>(IranCidrs.Count);
        foreach (var cidr in IranCidrs)
        {
            routes.Add(RouteEntry.FromCidr(cidr, gateway, interfaceIndex, metric, $"IR:{cidr}"));
        }
        return routes;
    }
